    const st = { id: 's' + ci + ',' + cj, ci, cj, cx: b.cx, cy: b.cy, R: 60, kind, name: REGION_NAMES[kind], key: U.hash2(ci, cj, seed + 641) & 0xffff, region: true, onLand: b.onLand };
    siteCache.set(k, st); return st;
